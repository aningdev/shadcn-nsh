import { afterEach, describe, expect, test } from "bun:test";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";

import { parse } from "jsonc-parser";

import { ensureAtPaths, nshTypePaths, NSH_TYPE_PATHS } from "./tsconfig";

// The base `.nsh/tsconfig.json` NSH writes: JSONC, its paths relative to its own directory.
const BASE = `// Generated by nsh.
{
  "compilerOptions": {
    "paths": {
      "nsh": ["./types/nsh/index.d.ts"],
      "nsh/*": ["./types/nsh/*.d.ts"],
      "*": ["./types/*.d.ts"],
      "extra": "./types/extra.d.ts"
    }
  }
}`;

// The same paths, each target rewritten for the app root.
const REWRITTEN: Record<string, string[]> = {
  nsh: ["./.nsh/types/nsh/index.d.ts"],
  "nsh/*": ["./.nsh/types/nsh/*.d.ts"],
  "*": ["./.nsh/types/*.d.ts"],
  extra: ["./.nsh/types/extra.d.ts"],
};

// The `tsconfig.json` `nsh init` writes, before `shadcn-nsh init` adds anything.
const NSH_INIT_TSCONFIG = `{
  "extends": "./.nsh/tsconfig.json",
  "include": ["**/*.ts", "**/*.tsx"]
}`;

let dir: string;

async function stage(files: Record<string, string>): Promise<string> {
  dir = await fs.mkdtemp(path.join(os.tmpdir(), "shadcn-nsh-tsconfig-"));
  for (const [rel, content] of Object.entries(files)) {
    const target = path.join(dir, rel);
    await fs.mkdir(path.dirname(target), { recursive: true });
    await fs.writeFile(target, content);
  }
  return dir;
}

const read = (rel: string) => fs.readFile(path.join(dir, rel), "utf8");

/** The `compilerOptions.paths` a written tsconfig declares, read as the JSONC it is. */
const pathsOf = (text: string): Record<string, string[]> | undefined =>
  (
    parse(text, undefined, { allowTrailingComma: true }) as {
      compilerOptions?: { paths?: Record<string, string[]> };
    }
  ).compilerOptions?.paths;

afterEach(async () => {
  if (dir) await fs.rm(dir, { recursive: true, force: true });
});

describe("nshTypePaths", () => {
  test("reads the base's paths, rewritten for the app root", async () => {
    const app = await stage({ ".nsh/tsconfig.json": BASE });
    expect(await nshTypePaths(app)).toEqual(REWRITTEN);
  });

  test("resolves every target through the .nsh directory, and passes wildcards through", async () => {
    const app = await stage({
      ".nsh/tsconfig.json": `{
  "compilerOptions": {
    "paths": {
      "pkg": ["../shared/types/index.d.ts", "./types/pkg.d.ts"],
      "*": "./*"
    }
  }
}`,
    });
    expect(await nshTypePaths(app)).toEqual({
      pkg: ["./shared/types/index.d.ts", "./.nsh/types/pkg.d.ts"],
      "*": ["./.nsh/*"],
    });
  });

  test("returns null when there is nothing to read", async () => {
    expect(await nshTypePaths(await stage({}))).toBeNull();
    const noPaths = await stage({ ".nsh/tsconfig.json": `{ "compilerOptions": {} }` });
    expect(await nshTypePaths(noPaths)).toBeNull();
    const broken = await stage({ ".nsh/tsconfig.json": `{ oops` });
    expect(await nshTypePaths(broken)).toBeNull();
  });
});

describe("ensureAtPaths", () => {
  test("writes a fresh tsconfig: the base's mappings restated, @/* last, no comment needed", async () => {
    const app = await stage({ ".nsh/tsconfig.json": BASE });
    expect(await ensureAtPaths(app)).toEqual({ status: "wrote" });
    expect(await read("tsconfig.json")).toBe(`{
  "extends": "./.nsh/tsconfig.json",
  "compilerOptions": {
    "paths": {
      "nsh": ["./.nsh/types/nsh/index.d.ts"],
      "nsh/*": ["./.nsh/types/nsh/*.d.ts"],
      "*": ["./.nsh/types/*.d.ts"],
      "extra": ["./.nsh/types/extra.d.ts"],
      "@/*": ["./*"]
    }
  },
  "include": ["**/*.ts", "**/*.tsx"]
}
`);
  });

  test("falls back to NSH's known mappings when there is no .nsh/tsconfig.json, and says so", async () => {
    const app = await stage({});
    expect(await ensureAtPaths(app)).toEqual({ status: "wrote" });
    const text = await read("tsconfig.json");
    expect(text).toContain("No .nsh/tsconfig.json to read");
    expect(pathsOf(text)).toEqual({ ...NSH_TYPE_PATHS, "@/*": ["./*"] });
  });

  test("merges into the tsconfig nsh init writes: base + @/* appended, rest kept", async () => {
    const app = await stage({ ".nsh/tsconfig.json": BASE, "tsconfig.json": NSH_INIT_TSCONFIG });
    expect(await ensureAtPaths(app)).toEqual({ status: "merged", detail: "base" });
    expect(await read("tsconfig.json")).toBe(`{
  "extends": "./.nsh/tsconfig.json",
  "include": ["**/*.ts", "**/*.tsx"],
  "compilerOptions": {
    "paths": {
      "nsh": ["./.nsh/types/nsh/index.d.ts"],
      "nsh/*": ["./.nsh/types/nsh/*.d.ts"],
      "*": ["./.nsh/types/*.d.ts"],
      "extra": ["./.nsh/types/extra.d.ts"],
      "@/*": ["./*"]
    }
  }
}`);
  });

  test("merges into an existing compilerOptions, keeping its keys and comments", async () => {
    const app = await stage({
      ".nsh/tsconfig.json": BASE,
      "tsconfig.json": `{
  // my app's settings
  "extends": "./.nsh/tsconfig.json",
  "compilerOptions": {
    "strict": true
  }
}`,
    });
    expect(await ensureAtPaths(app)).toEqual({ status: "merged", detail: "base" });
    expect(await read("tsconfig.json")).toBe(`{
  // my app's settings
  "extends": "./.nsh/tsconfig.json",
  "compilerOptions": {
    "strict": true,
    "paths": {
      "nsh": ["./.nsh/types/nsh/index.d.ts"],
      "nsh/*": ["./.nsh/types/nsh/*.d.ts"],
      "*": ["./.nsh/types/*.d.ts"],
      "extra": ["./.nsh/types/extra.d.ts"],
      "@/*": ["./*"]
    }
  }
}`);
  });

  test("indents the way the file itself does, not the way this CLI would", async () => {
    const app = await stage({
      ".nsh/tsconfig.json": BASE,
      "tsconfig.json": `{
\t"extends": "./.nsh/tsconfig.json",
\t"include": ["**/*.ts", "**/*.tsx"]
}`,
    });
    expect(await ensureAtPaths(app)).toEqual({ status: "merged", detail: "base" });
    expect(await read("tsconfig.json")).toBe(`{
\t"extends": "./.nsh/tsconfig.json",
\t"include": ["**/*.ts", "**/*.tsx"],
\t"compilerOptions": {
\t\t"paths": {
\t\t\t"nsh": ["./.nsh/types/nsh/index.d.ts"],
\t\t\t"nsh/*": ["./.nsh/types/nsh/*.d.ts"],
\t\t\t"*": ["./.nsh/types/*.d.ts"],
\t\t\t"extra": ["./.nsh/types/extra.d.ts"],
\t\t\t"@/*": ["./*"]
\t\t}
\t}
}`);
  });

  test("fills an empty paths in place, which replaces the base's just as much as none at all", async () => {
    const app = await stage({
      ".nsh/tsconfig.json": BASE,
      "tsconfig.json": `{
  "compilerOptions": {
    "paths": {}
  }
}`,
    });
    expect(await ensureAtPaths(app)).toEqual({ status: "merged", detail: "base" });
    const text = await read("tsconfig.json");
    expect(pathsOf(text)).toEqual({ ...REWRITTEN, "@/*": ["./*"] });
    // One `paths` key, in its original place.
    expect(text.split('"paths"').length - 1).toBe(1);
  });

  test("adds only @/* to paths the app already has", async () => {
    const app = await stage({
      "tsconfig.json": `{
  "compilerOptions": {
    "paths": {
      "utils/*": ["./src/utils/*"]
    }
  }
}`,
    });
    expect(await ensureAtPaths(app)).toEqual({ status: "merged" });
    const text = await read("tsconfig.json");
    expect(pathsOf(text)).toEqual({ "utils/*": ["./src/utils/*"], "@/*": ["./*"] });
    expect(text).not.toContain(".nsh/types");
  });

  test("is a no-op when @/* already maps to ./*, in either form", async () => {
    for (const targets of ['["./*"]', '"./*"']) {
      const app = await stage({
        "tsconfig.json": `{
  "compilerOptions": {
    "paths": {
      "@/*": ${targets}
    }
  }
}`,
      });
      expect(await ensureAtPaths(app)).toEqual({ status: "present" });
      expect(await read("tsconfig.json")).toBe(`{
  "compilerOptions": {
    "paths": {
      "@/*": ${targets}
    }
  }
}`);
    }
  });

  test("keeps a conflicting @/* and says where it maps", async () => {
    const app = await stage({
      "tsconfig.json": `{
  "compilerOptions": {
    "paths": {
      "@/*": ["./src/*"]
    }
  }
}`,
    });
    expect(await ensureAtPaths(app)).toEqual({
      status: "conflict",
      detail: '["./src/*"]',
    });
    expect(await read("tsconfig.json")).toBe(`{
  "compilerOptions": {
    "paths": {
      "@/*": ["./src/*"]
    }
  }
}`);
  });

  test("keeps a tsconfig it cannot read, and says why", async () => {
    const app = await stage({ "tsconfig.json": `{ oops` });
    const at = await ensureAtPaths(app);
    expect(at.status).toBe("warn");
    expect(at.detail).toContain("could not be read as JSONC");
    expect(await read("tsconfig.json")).toBe(`{ oops`);
  });
});
