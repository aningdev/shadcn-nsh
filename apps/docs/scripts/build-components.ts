/**
 * Builds the docs' component list from the registry and the pages, and writes
 * `src/lib/components.generated.ts`.
 *
 *   bun run docs:components
 *
 * Every `registry:ui` item with a page in `src/pages/docs/components` is one
 * entry: the page's frontmatter title and description when it has them, the
 * registry's otherwise. The order is by slug. `check:pages` fails when the
 * checked-in file no longer matches this plan.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import type { ComponentDoc } from "../src/lib/components.types";
import { NSH_ELEMENTS } from "../src/lib/nsh-elements";

const docs = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repo = path.resolve(docs, "../..");
const pagesDir = path.join(docs, "src/pages/docs/components");
const outFile = path.join(docs, "src/lib/components.generated.ts");

type RegistryItem = {
  name: string;
  type: string;
  title?: string;
  description?: string;
};

type PageMeta = {
  title?: string;
  description?: string;
  demo?: string;
};

/** The frontmatter lines this build needs. Values are one line, optionally quoted. */
export function readPageMeta(source: string): PageMeta {
  const match = /^---\r?\n([\s\S]*?)\r?\n---/.exec(source);
  if (!match) return {};
  const meta: PageMeta = {};
  for (const line of match[1]!.split(/\r?\n/)) {
    const pair = /^([A-Za-z][\w-]*):\s*(.*)$/.exec(line);
    if (!pair) continue;
    const key = pair[1]!;
    let value = pair[2]!.trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (key === "title" || key === "description" || key === "demo") meta[key] = value;
  }
  return meta;
}

/** Every registry:ui item that has a page, as the site should list it. */
export function componentPlan(): ComponentDoc[] {
  const registry = JSON.parse(fs.readFileSync(path.join(repo, "registry.json"), "utf8")) as {
    items: RegistryItem[];
  };
  const pages = new Set(
    fs
      .readdirSync(pagesDir)
      .filter((file) => file.endsWith(".md"))
      .map((file) => file.slice(0, -3)),
  );

  const plan: ComponentDoc[] = [];
  for (const item of registry.items) {
    if (item.type !== "registry:ui" || !pages.has(item.name)) continue;
    const meta = readPageMeta(fs.readFileSync(path.join(pagesDir, `${item.name}.md`), "utf8"));
    plan.push({
      slug: item.name,
      title: meta.title ?? item.title ?? item.name,
      nshElement: item.name in NSH_ELEMENTS ? (NSH_ELEMENTS[item.name] ?? null) : item.name,
      description: meta.description ?? item.description ?? "",
    });
  }
  return plan.sort((a, b) => a.slug.localeCompare(b.slug));
}

/** The generated module, formatted as the repository's formatter leaves it. */
export function renderComponents(plan: ComponentDoc[]): string {
  const entries = plan
    .map(
      (entry) => `  {
    slug: ${JSON.stringify(entry.slug)},
    title: ${JSON.stringify(entry.title)},
    nshElement: ${entry.nshElement === null ? "null" : JSON.stringify(entry.nshElement)},
    description: ${JSON.stringify(entry.description)},
  },`,
    )
    .join("\n");
  return `// Generated by \`bun run docs:components\` from registry.json and the pages' frontmatter.
// Do not edit: add or change a page, then run the script again. Checked by \`bun run check:pages\`.
import type { ComponentDoc } from "./components.types";

export const components: ComponentDoc[] = [
${entries}
];
`;
}

/** True when the checked-in module lists the same entries as the plan. */
export function isCurrent(plan: ComponentDoc[], current: ComponentDoc[]): boolean {
  return JSON.stringify(current) === JSON.stringify(plan);
}

if (import.meta.main) {
  const plan = componentPlan();
  if (process.argv.includes("--check")) {
    const mod = (await import(pathToFileURL(outFile).href)) as { components: ComponentDoc[] };
    if (!isCurrent(plan, mod.components)) {
      console.error("components.generated.ts is out of date; run `bun run docs:components`.");
      process.exit(1);
    }
    console.log(`components.generated.ts is current (${plan.length} components).`);
  } else {
    fs.writeFileSync(outFile, renderComponents(plan));
    console.log(`Wrote ${path.relative(repo, outFile)} (${plan.length} components).`);
  }
}
