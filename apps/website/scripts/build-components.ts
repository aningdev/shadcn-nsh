/**
 * Builds the docs' component list from the catalog, the pages and the official tables, and writes
 * `src/lib/components.generated.ts`.
 *
 *   bun run docs:components
 *
 * Every component is one entry: the page's frontmatter title and description when it has them,
 * the registry's otherwise, plus its kind and the official components it stands in for. Both come
 * from `src/lib/official.ts`: the rows there are the one table, and the kind is derived from them
 * (`src/lib/kinds.ts`). The order is by kind, then title — the order the sidebar and the index
 * list them in, titles being what those lists show. `check:pages` fails when the checked-in file
 * no longer matches this plan.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { catalog } from "../../../scripts/catalog";
import type { ComponentDoc } from "../src/lib/components";
import { KINDS, kindOf } from "../src/lib/kinds";
import { nshElementOf, shadcnOf } from "../src/lib/official";

const docs = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repo = path.resolve(docs, "../..");
const outFile = path.join(docs, "src/lib/components.generated.ts");

type PageMeta = {
  title?: string;
  description?: string;
  demo?: string;
};

/** The frontmatter lines this build needs. Values are one line, optionally quoted. */
export function readPageMeta(source: string): PageMeta {
  const match = /^---\r?\n([\s\S]*?)\r?\n---/.exec(source);
  if (!match) return {};
  const meta: PageMeta = {};
  for (const line of match[1]!.split(/\r?\n/)) {
    const pair = /^([A-Za-z][\w-]*):\s*(.*)$/.exec(line);
    if (!pair) continue;
    const key = pair[1]!;
    let value = pair[2]!.trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (key === "title" || key === "description" || key === "demo") meta[key] = value;
  }
  return meta;
}

/** Every component, as the site should list it: by kind, then title. */
export function componentPlan(): ComponentDoc[] {
  const plan: ComponentDoc[] = [];
  for (const { id, item, page } of catalog().components) {
    const meta = readPageMeta(fs.readFileSync(page, "utf8"));
    plan.push({
      slug: id,
      title: meta.title ?? item.title ?? id,
      kind: kindOf(id),
      shadcn: shadcnOf(id) ?? null,
      nshElement: nshElementOf(id) ?? null,
      description: meta.description ?? item.description ?? "",
    });
  }
  const rank = (kind: ComponentDoc["kind"]) => KINDS.indexOf(kind);
  return plan.sort(
    (a, b) =>
      rank(a.kind) - rank(b.kind) || a.title.localeCompare(b.title) || a.slug.localeCompare(b.slug),
  );
}

/** The generated module, formatted as the repository's formatter leaves it. */
export function renderComponents(plan: ComponentDoc[]): string {
  const entries = plan
    .map(
      (entry) => `  {
    slug: ${JSON.stringify(entry.slug)},
    title: ${JSON.stringify(entry.title)},
    kind: ${JSON.stringify(entry.kind)},
    shadcn: ${entry.shadcn === null ? "null" : JSON.stringify(entry.shadcn)},
    nshElement: ${entry.nshElement === null ? "null" : JSON.stringify(entry.nshElement)},
    description: ${JSON.stringify(entry.description)},
  },`,
    )
    .join("\n");
  return `// Generated by \`bun run docs:components\` from registry.json and the pages' frontmatter.
// Do not edit: add or change a page, then run the script again. Checked by \`bun run check:pages\`.
import type { ComponentDoc } from "./components";

export const components: ComponentDoc[] = [
${entries}
];
`;
}

/** True when the checked-in module lists the same entries as the plan. */
export function isCurrent(plan: ComponentDoc[], current: ComponentDoc[]): boolean {
  return JSON.stringify(current) === JSON.stringify(plan);
}

if (import.meta.main) {
  const plan = componentPlan();
  if (process.argv.includes("--check")) {
    const mod = (await import(pathToFileURL(outFile).href)) as { components: ComponentDoc[] };
    if (!isCurrent(plan, mod.components)) {
      console.error("components.generated.ts is out of date; run `bun run docs:components`.");
      process.exit(1);
    }
    console.log(`components.generated.ts is current (${plan.length} components).`);
  } else {
    fs.writeFileSync(outFile, renderComponents(plan));
    console.log(`Wrote ${path.relative(repo, outFile)} (${plan.length} components).`);
  }
}
